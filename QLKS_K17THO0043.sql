CREATE TABLE KHACHHANG (
MAKH VARCHAR(10) PRIMARY KEY,
TENKH NVARCHAR(30) NOT NULL,        --EDIT
SODIENTHOAI VARCHAR(15),
CCCD VARCHAR(20) UNIQUE,    ---CCCD HOẶC PASSPORT
EMAIL VARCHAR(100)
)
CREATE TABLE NHANVIEN (
MANV VARCHAR(10) PRIMARY KEY,
TENNV NVARCHAR(30),        --EDIT
CHUCVU NVARCHAR(20),  ---LỄ TÂN, BUỒNG PHÒNG, QUẢN LÝ
TRANGTHAILAMVIEC BIT ---1-ĐANG LÀM,0-ĐÃ NGHỈ
)
CREATE TABLE PHIEUDATPHONG (
MAPHIEUDAT VARCHAR(10) PRIMARY KEY,
MAKH VARCHAR(10) NOT NULL,   --FK KHACHHANG
MANV_LAPPHIEU VARCHAR(10) NOT NULL,		--FK NHANVIEN(MANV)
NGAYDAT DATE,
TIENCOC DECIMAL(18,2) DEFAULT 0,
TRANGTHAIPHIEU NVARCHAR(20)
)
CREATE TABLE CHITIETDATPHONG (
MACHITIET VARCHAR(10) PRIMARY KEY,
MAPHIEUDAT VARCHAR(10) NOT NULL,      --FK PHIEUDATPHONG,
MAPHONG VARCHAR(10) NOT NULL,		--FK PHONG
NGAYCHECKINDUKIEN DATETIME NOT NULL,
NGAYCHECKOUTDUKIEN DATETIME NOT NULL,
NGAYCHECKINTHUCTE DATETIME NULL,
NGAYCHECKOUTTHUCTE DATETIME NULL,
DONGIADAT DECIMAL(18,2) NOT NULL DEFAULT 0
)
CREATE TABLE LOAIDICHVU (
MALOAIDV VARCHAR(10) PRIMARY KEY,
TENLOAIDICHVU NVARCHAR(30) NOT NULL
)
CREATE TABLE DICHVU (
MADV VARCHAR(10) PRIMARY KEY,
MALOAIDV VARCHAR(10) NOT NULL,   ---FK LOAIDICHVU
TENDV NVARCHAR(30) NOT NULL,
DONGIADV DECIMAL(18,2) NOT NULL DEFAULT 0,    --EDIT
DONVITINH NVARCHAR(20)   ---LON, CHAI, LẦN, BỘ---
)
CREATE TABLE SUDUNGDICHVU (
MASUDUNG VARCHAR(10) PRIMARY KEY,
MACHITIET VARCHAR(10) NOT NULL,    --FK CHITIETDATPHONG
MADV VARCHAR(10) NOT NULL,		--FK DICHVU
DONGIADV DECIMAL(18,2) NOT NULL DEFAULT 0,   --FK DICHVU
SOLUONG INT NOT NULL CHECK(SOLUONG > 0),
THOIGIANSUDUNG DATETIME DEFAULT GETDATE(),
THANHTIEN AS SOLUONG * DONGIADV
)
CREATE TABLE HOADON (
MAHOADON VARCHAR(10) PRIMARY KEY,
MAPHIEUDAT VARCHAR(10) NOT NULL,		--FK PHIEUDATPHONG
MANV_THUTIEN VARCHAR(10) NOT NULL,			--FK NHANVIEN(MANV)
NGAYTHANHTOAN DATETIME DEFAULT GETDATE(),
TONGTIENPHONG DECIMAL(18,2) NOT NULL DEFAULT 0,
TONGTIENDICHVU DECIMAL(18,2) NOT NULL DEFAULT 0,
PHUTHU DECIMAL(18,2) DEFAULT 0,
TIENCOC DECIMAL(18,2) DEFAULT 0,    --FK PHIEUDATPHONG
TIENPHAITRA AS (TONGTIENPHONG + TONGTIENDICHVU + PHUTHU - TIENCOC),
PHUONGTHUCTT NVARCHAR(30)		--TIỀN MẶT, CHUYỂN KHOẢN, THẺ,...
)
