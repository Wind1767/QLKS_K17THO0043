CREATE TABLE LOAIPHONG (
MALOAI VARCHAR(10) PRIMARY KEY,
TENLOAI NVARCHAR(30) NOT NULL,
GIATHEONGAY DECIMAL(18,2) NOT NULL DEFAULT 0 ,
SONGUOITOIDA INT NOT NULL CHECK(SONGUOITOIDA > 0)
