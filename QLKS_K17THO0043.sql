CREATE TABLE PHONG (
MAPHONG VARCHAR(10) PRIMARY KEY,
MALOAI VARCHAR(10) NOT NULL,   --FK LOAIPHONG
TANG INT,
TRANGTHAI NVARCHAR(15) DEFAULT N'TRỐNG'   ---Trống, Đang ở, Bảo trì... 
